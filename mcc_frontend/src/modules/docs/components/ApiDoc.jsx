import { useEffect, useRef, useState } from "react";
import env from "../../../config/env.js";
import useResolvedTheme from "../../../hooks/useResolvedTheme.js";

// Swagger UI ships light only. In the dark theme it is inverted in place, with
// hue rotated back so the method colours (GET blue, POST green) keep their meaning.
const SWAGGER_DARK = `
  html { filter: invert(0.92) hue-rotate(180deg); background: #fff; }
  .swagger-ui .topbar { display: none; }
`;
const SWAGGER_LIGHT = ".swagger-ui .topbar { display: none; }";

/** The backend's own OpenAPI description, in Swagger UI, callable against the running system. */
export default function ApiDoc() {
  const frame = useRef(null);
  const [loaded, setLoaded] = useState(false);
  const dark = useResolvedTheme() === "dark";

  useEffect(() => {
    const doc = frame.current?.contentDocument;
    if (!loaded || !doc) return;
    let style = doc.getElementById("mcc-theme");
    if (!style) {
      style = doc.createElement("style");
      style.id = "mcc-theme";
      doc.head.appendChild(style);
    }
    style.textContent = dark ? SWAGGER_DARK : SWAGGER_LIGHT;
  }, [loaded, dark]);

  return (
    <article className="doc doc-api">
      <div className="api-head">
        <div>
          <h1>REST API</h1>
          <p className="lead">
            Generated by the backend from its own code (OpenAPI 3). Open an endpoint and press <b>Try it out</b> to call it
            against the running system.
          </p>
        </div>
        <div className="api-links">
          <a href={`${env.apiBaseUrl}/swagger-ui.html`} target="_blank" rel="noreferrer">
            Open full screen ↗
          </a>
          <a href={`${env.apiBaseUrl}/v3/api-docs`} target="_blank" rel="noreferrer">
            OpenAPI JSON ↗
          </a>
        </div>
      </div>
      <div className="swagger-wrap">
        {!loaded && <div className="doc-loading">Loading Swagger UI…</div>}
        <iframe
          ref={frame}
          title="Swagger UI for the OrbLinx MCC API"
          src={`${env.apiBaseUrl}/swagger-ui/index.html`}
          onLoad={() => setLoaded(true)}
          className={loaded ? "" : "hidden-frame"}
        />
      </div>
    </article>
  );
}
